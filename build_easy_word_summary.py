import os
import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import parse_xml
from docx.oxml.ns import nsdecls

def create_document():
    doc = docx.Document()

    # Page Margins 1 inch
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1)
        section.right_margin = Inches(1)

    # Styles
    normal_style = doc.styles['Normal']
    normal_style.font.name = 'TH Sarabun New'
    normal_style.font.size = Pt(14)
    normal_style.font.color.rgb = RGBColor(30, 41, 59)
    normal_style.paragraph_format.line_spacing = 1.15
    normal_style.paragraph_format.space_after = Pt(4)

    def set_cell_background(cell, fill_hex):
        tcPr = cell._tc.get_or_add_tcPr()
        shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{fill_hex}"/>')
        tcPr.append(shd)

    def set_cell_margins(cell, top=120, bottom=120, left=180, right=180):
        tcPr = cell._tc.get_or_add_tcPr()
        tcMar = parse_xml(
            f'<w:tcMar {nsdecls("w")}>'
            f'<w:top w:w="{top}" w:type="dxa"/>'
            f'<w:bottom w:w="{bottom}" w:type="dxa"/>'
            f'<w:left w:w="{left}" w:type="dxa"/>'
            f'<w:right w:w="{right}" w:type="dxa"/>'
            f'</w:tcMar>'
        )
        tcPr.append(tcMar)

    def set_callout_border(cell, border_hex="2563EB", border_size="32"):
        tcPr = cell._tc.get_or_add_tcPr()
        borders = parse_xml(
            f'<w:tcBorders {nsdecls("w")}>'
            f'<w:top w:val="none"/>'
            f'<w:left w:val="single" w:sz="{border_size}" w:space="0" w:color="{border_hex}"/>'
            f'<w:bottom w:val="none"/>'
            f'<w:right w:val="none"/>'
            f'</w:tcBorders>'
        )
        tcPr.append(borders)

    def add_h1(text):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(16)
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.bold = True
        run.font.name = 'TH Sarabun New'
        run.font.size = Pt(20)
        run.font.color.rgb = RGBColor(30, 58, 138)
        return p

    def add_h2(text):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(12)
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.bold = True
        run.font.name = 'TH Sarabun New'
        run.font.size = Pt(16.5)
        run.font.color.rgb = RGBColor(37, 99, 235)
        return p

    def add_h3(text):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.bold = True
        run.font.name = 'TH Sarabun New'
        run.font.size = Pt(15)
        run.font.color.rgb = RGBColor(15, 118, 110)
        return p

    def add_callout(quote_title, quote_text, plain_explanation, action_text="", connection_text=""):
        table = doc.add_table(rows=1, cols=1)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = False
        table.columns[0].width = Inches(6.5)

        cell = table.cell(0, 0)
        set_cell_background(cell, "F8FAFC")
        set_callout_border(cell, "2563EB", "32")
        set_cell_margins(cell, top=140, bottom=140, left=200, right=200)

        p1 = cell.paragraphs[0]
        p1.paragraph_format.space_after = Pt(4)
        p1.paragraph_format.line_spacing = 1.15
        run_qt = p1.add_run(f"📜 ข้อความต้นฉบับ / นิยามวิชาการ: {quote_title}\n")
        run_qt.bold = True
        run_qt.font.name = "TH Sarabun New"
        run_qt.font.size = Pt(14)
        run_qt.font.color.rgb = RGBColor(30, 58, 138)

        run_q = p1.add_run(f"\"{quote_text}\"\n")
        run_q.italic = True
        run_q.font.name = "TH Sarabun New"
        run_q.font.size = Pt(13)
        run_q.font.color.rgb = RGBColor(71, 85, 105)

        p2 = cell.add_paragraph()
        p2.paragraph_format.space_before = Pt(6)
        p2.paragraph_format.space_after = Pt(4)
        p2.paragraph_format.line_spacing = 1.15
        run_et = p2.add_run("💡 ถอดรหัสคำอธิบายภาษาคน & ภาพจำ:\n")
        run_et.bold = True
        run_et.font.name = "TH Sarabun New"
        run_et.font.size = Pt(14)
        run_et.font.color.rgb = RGBColor(180, 83, 9)

        run_e = p2.add_run(plain_explanation + "\n")
        run_e.font.name = "TH Sarabun New"
        run_e.font.size = Pt(13.5)
        run_e.font.color.rgb = RGBColor(30, 41, 59)

        if action_text:
            p3 = cell.add_paragraph()
            p3.paragraph_format.space_before = Pt(4)
            p3.paragraph_format.space_after = Pt(2)
            p3.paragraph_format.line_spacing = 1.15
            run_at = p3.add_run("🛠️ ครูนำไปใช้ทำอะไรหน้างาน: ")
            run_at.bold = True
            run_at.font.name = "TH Sarabun New"
            run_at.font.size = Pt(13)
            run_at.font.color.rgb = RGBColor(13, 148, 136)

            run_a = p3.add_run(action_text)
            run_a.font.name = "TH Sarabun New"
            run_a.font.size = Pt(13)
            run_a.font.color.rgb = RGBColor(51, 65, 85)

        if connection_text:
            p4 = cell.add_paragraph()
            p4.paragraph_format.space_before = Pt(4)
            p4.paragraph_format.space_after = Pt(2)
            p4.paragraph_format.line_spacing = 1.15
            run_ct = p4.add_run("🔗 จุดเชื่อมโยง: ")
            run_ct.bold = True
            run_ct.font.name = "TH Sarabun New"
            run_ct.font.size = Pt(13)
            run_ct.font.color.rgb = RGBColor(124, 58, 237)

            run_c = p4.add_run(connection_text)
            run_c.font.name = "TH Sarabun New"
            run_c.font.size = Pt(13)
            run_c.font.color.rgb = RGBColor(51, 65, 85)

        p_spacer = doc.add_paragraph()
        p_spacer.paragraph_format.space_before = Pt(2)
        p_spacer.paragraph_format.space_after = Pt(4)

    # ==================== COVER / HEADER ====================
    title_p = doc.add_paragraph()
    title_p.paragraph_format.space_before = Pt(10)
    title_p.paragraph_format.space_after = Pt(2)
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r_title = title_p.add_run("คู่มือถอดรหัสความรู้และสรุปเชื่อมโยง EDP3502\nการช่วยเหลือและให้คำปรึกษาผู้เรียน (บทที่ 5 – 11)")
    r_title.bold = True
    r_title.font.name = 'TH Sarabun New'
    r_title.font.size = Pt(24)
    r_title.font.color.rgb = RGBColor(30, 58, 138)

    sub_p = doc.add_paragraph()
    sub_p.paragraph_format.space_after = Pt(14)
    sub_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r_sub = sub_p.add_run("ฉบับเน้นคำอธิบายภาษาคนเข้าใจง่าย • ยกข้อความต้นฉบับเปรียบเทียบ • เรียงลำดับตามไฟล์ 5 ถึง 11")
    r_sub.font.name = 'TH Sarabun New'
    r_sub.font.size = Pt(15)
    r_sub.font.color.rgb = RGBColor(100, 116, 139)

